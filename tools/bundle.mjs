#!/usr/bin/env node
/**
 * RepoVault bundler — index.html + app/*.js  →  repovault.html (one file, no imports).
 *
 * Why: ES modules need a web server; a single classic-script file works from
 * file://, from a USB stick, and inside sandboxed preview iframes. The modules
 * stay the source of truth (they're what the tests import) and this script only
 * concatenates them, so there is no second copy of the logic to keep in sync.
 *
 * It also fails loudly on duplicate top-level declarations, because flattening
 * modules into one scope is exactly where that would silently bite.
 *
 *   node tools/bundle.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

// Dependency order — every import in the app must point at an earlier file.
const MODULES = [
  'app/core/util.js',
  'app/core/crypto.js',
  'app/adapters/github.js',
  'app/adapters/memory.js',
  'app/core/vault.js',
  'app/ui/app.js',
];

const EXPORTS = [
  'Vault', 'GitHubAdapter', 'GitHubError', 'MemoryAdapter',
  'encryptBytes', 'decryptBytes', 'deriveVaultKey', 'isEncryptedBytes',
  'b64encode', 'b64decode', 'formatBytes', 'kindOf', 'LIMITS', 'mount',
];

function stripModuleSyntax(source, file) {
  const before = source;
  const out = source
    // drop import statements (single or multi line)
    .replace(/^[ \t]*import\s+[\s\S]*?from\s*['"][^'"]+['"];?[ \t]*$/gm, '')
    .replace(/^[ \t]*import\s*['"][^'"]+['"];?[ \t]*$/gm, '')
    // drop bare re-export statements
    .replace(/^[ \t]*export\s*\{[^}]*\};?[ \t]*$/gm, '')
    // unwrap `export const|let|var|function|class|async function`
    .replace(/^([ \t]*)export\s+(?=(const|let|var|function|class|async)\b)/gm, '$1');
  if (/^\s*(import|export)\b/m.test(out)) {
    const line = out.split('\n').find((l) => /^\s*(import|export)\b/.test(l));
    throw new Error(`${file}: unhandled module syntax → ${line.trim().slice(0, 80)}`);
  }
  return { code: out, changed: out !== before };
}

function topLevelNames(code) {
  const names = new Set();
  const re = /^(?:const|let|var|function|class|async function)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(code))) names.add(m[1]);
  return names;
}

function build() {
  const html = readFileSync(join(root, 'index.html'), 'utf8');
  const scriptTag = /<script\s+type="module"\s+src="\.\/app\/ui\/app\.js"\s*><\/script>/;
  if (!scriptTag.test(html)) throw new Error('index.html: could not find the module entry script tag');

  const seen = new Map();
  const chunks = [];
  for (const file of MODULES) {
    const raw = readFileSync(join(root, file), 'utf8');
    const { code } = stripModuleSyntax(raw, file);
    for (const name of topLevelNames(code)) {
      if (seen.has(name)) throw new Error(`duplicate top-level binding "${name}" in ${file} (already declared in ${seen.get(name)}) — rename one of them`);
      seen.set(name, file);
    }
    chunks.push(`/* ==== ${file} ${'='.repeat(Math.max(0, 64 - file.length))} */\n${code.trim()}\n`);
  }

  const banner = `/* RepoVault — single-file build. Generated by tools/bundle.mjs from index.html + app/**.
   Do not edit here: edit the modules and re-run \`node tools/bundle.mjs\`. */
(function () {
"use strict";
`;
  const footer = `
/* expose the core for console tinkering and the bundle integrity test */
globalThis.RepoVault = { ${EXPORTS.join(', ')} };
})();
`;
  const bundle = banner + chunks.join('\n') + footer;
  new vm.Script(bundle); // throws on any syntax error before we ship it

  const out = html.replace(scriptTag, `<script>\n${bundle}</script>`);
  const target = join(root, 'repovault.html');
  writeFileSync(target, out);
  return { target, size: out.length, modules: MODULES.length, bindings: seen.size };
}

const result = build();
console.log(`✓ bundled ${result.modules} modules (${result.bindings} top-level bindings) → repovault.html (${(result.size / 1024).toFixed(1)} KB)`);
export { build, stripModuleSyntax, MODULES };
